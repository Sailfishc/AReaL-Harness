test("experimental consumers require exact entries and reject stale allowances", async (t) => {
  const { verifyExperimentalImports } = await import("./documents.mjs");
  const root = await mkdtemp(join(tmpdir(), "areal-ui-entries-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(join(root, "renderer/src"), { recursive: true });
  await writeFile(
    join(root, "renderer/src/consumer.ts"),
    'import { Spinner } from "@areal/ui/experimental";\n',
  );
  const allowance = {
    file: "renderer/src/consumer.ts",
    symbol: "Spinner",
    owner: "GUI component owner",
    exitCondition: "Assess contract and production consumers before graduation.",
  };
  await assert.rejects(
    verifyExperimentalImports(root, []),
    /unlisted experimental import.*Spinner/,
  );
  assert.equal(await verifyExperimentalImports(root, [allowance]), 1);
  await writeFile(join(root, "renderer/src/consumer.ts"), 'import { Button } from "@areal/ui";\n');
  await assert.rejects(
    verifyExperimentalImports(root, [allowance]),
    /stale experimental allowance.*Spinner/,
  );
  for (const entry of ["wip", "src/internal"]) {
    await writeFile(
      join(root, "renderer/src/consumer.ts"),
      `import { Spinner } from "@areal/ui/${entry}";\n`,
    );
    await assert.rejects(verifyExperimentalImports(root, []), /retired or deep UI import/);
  }
  for (const entry of ["experimental", "wip", "src/internal"]) {
    await writeFile(
      join(root, "renderer/src/consumer.ts"),
      `const lazy = () => import("@areal/ui/${entry}");\n`,
    );
    await assert.rejects(verifyExperimentalImports(root, []), /UI import/);
  }
});

test("palette role metadata covers actual variables and aliases resolve to known roles", async () => {
  const { renderTokenReference } = await import("./foundations.mjs");
  const result = renderFoundations(tokens);
  const paletteVariables = () => ({ "--color-background": "#ffffff" });
  const missing = structuredClone(tokens);
  missing.palette = { roles: {} };
  assert.throws(
    () => renderTokenReference(missing, result.themes, paletteVariables),
    /palette metadata.*color-background/,
  );
  const invalid = structuredClone(tokens);
  invalid.palette.roles["--color-background"].alias = "--color-missing";
  assert.throws(
    () => renderTokenReference(invalid, result.themes, paletteVariables),
    /unknown palette alias/,
  );
});
